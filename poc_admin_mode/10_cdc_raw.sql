-- =====================================================================
-- 10 CDC LANDING: append-only change tables + per-table LSN checkpoint
-- Each row = one change from SQL Server CDC (I/U/D) or one snapshot row (S).
-- _CDC_LSN / _CDC_SEQVAL are fixed-width hex, so string order = commit order.
-- Future grants on RAW (01 bootstrap) give LOADER write and TRANSFORMER read.
-- =====================================================================
USE ROLE POC_ADMIN;
USE SCHEMA SALES_DW_PROD.RAW;

CREATE TABLE IF NOT EXISTS CUSTOMER_CT (
    CUSTOMERID NUMBER(38,0), CUSTOMERCODE VARCHAR(20), FIRSTNAME VARCHAR(50), LASTNAME VARCHAR(50),
    EMAIL VARCHAR(255), PHONE VARCHAR(30), CITY VARCHAR(100), COUNTRYCODE VARCHAR(2), SEGMENT VARCHAR(20),
    MODIFIEDDATE TIMESTAMP_NTZ(3),
    _CDC_OP VARCHAR(1), _CDC_LSN VARCHAR(20), _CDC_SEQVAL VARCHAR(20), _CDC_COMMIT_TS TIMESTAMP_NTZ(3),
    _LOADED_AT TIMESTAMP_LTZ DEFAULT CURRENT_TIMESTAMP(), _BATCH_ID VARCHAR(64), _SOURCE_SYSTEM VARCHAR(30) DEFAULT 'SalesOLTP');

CREATE TABLE IF NOT EXISTS PRODUCT_CT (
    PRODUCTID NUMBER(38,0), SKU VARCHAR(30), PRODUCTNAME VARCHAR(200), CATEGORY VARCHAR(50), SUBCATEGORY VARCHAR(50),
    LISTPRICE NUMBER(38,4), STANDARDCOST NUMBER(38,4), ISACTIVE BOOLEAN, MODIFIEDDATE TIMESTAMP_NTZ(3),
    _CDC_OP VARCHAR(1), _CDC_LSN VARCHAR(20), _CDC_SEQVAL VARCHAR(20), _CDC_COMMIT_TS TIMESTAMP_NTZ(3),
    _LOADED_AT TIMESTAMP_LTZ DEFAULT CURRENT_TIMESTAMP(), _BATCH_ID VARCHAR(64), _SOURCE_SYSTEM VARCHAR(30) DEFAULT 'SalesOLTP');

CREATE TABLE IF NOT EXISTS SALESORDERHEADER_CT (
    SALESORDERID NUMBER(38,0), ORDERNUMBER VARCHAR(25), CUSTOMERID NUMBER(38,0), ORDERDATE TIMESTAMP_NTZ(3),
    STATUS NUMBER(3,0), CHANNEL VARCHAR(20), CURRENCYCODE VARCHAR(3), MODIFIEDDATE TIMESTAMP_NTZ(3),
    _CDC_OP VARCHAR(1), _CDC_LSN VARCHAR(20), _CDC_SEQVAL VARCHAR(20), _CDC_COMMIT_TS TIMESTAMP_NTZ(3),
    _LOADED_AT TIMESTAMP_LTZ DEFAULT CURRENT_TIMESTAMP(), _BATCH_ID VARCHAR(64), _SOURCE_SYSTEM VARCHAR(30) DEFAULT 'SalesOLTP');

CREATE TABLE IF NOT EXISTS SALESORDERDETAIL_CT (
    SALESORDERDETAILID NUMBER(38,0), SALESORDERID NUMBER(38,0), PRODUCTID NUMBER(38,0), ORDERQTY NUMBER(5,0),
    UNITPRICE NUMBER(38,4), UNITPRICEDISCOUNT NUMBER(38,4), MODIFIEDDATE TIMESTAMP_NTZ(3),
    _CDC_OP VARCHAR(1), _CDC_LSN VARCHAR(20), _CDC_SEQVAL VARCHAR(20), _CDC_COMMIT_TS TIMESTAMP_NTZ(3),
    _LOADED_AT TIMESTAMP_LTZ DEFAULT CURRENT_TIMESTAMP(), _BATCH_ID VARCHAR(64), _SOURCE_SYSTEM VARCHAR(30) DEFAULT 'SalesOLTP');

CREATE TABLE IF NOT EXISTS CDC_CHECKPOINT (
    TABLE_NAME VARCHAR(128) PRIMARY KEY,
    CAPTURE_INSTANCE VARCHAR(128),
    LAST_LSN VARCHAR(20),
    LAST_MODE VARCHAR(12),            -- SNAPSHOT / INCREMENTAL
    ROWS_LAST_RUN NUMBER,
    UPDATED_AT TIMESTAMP_LTZ);

-- Monitoring: change volume and lag per table
CREATE OR REPLACE VIEW SALES_DW_PROD.AUDIT.V_CDC_LAG AS
SELECT 'CUSTOMER' AS TABLE_NAME, _CDC_OP, COUNT(*) AS CHANGES, MAX(_CDC_COMMIT_TS) AS LAST_COMMIT_TS, MAX(_LOADED_AT) AS LAST_LOADED_AT FROM RAW.CUSTOMER_CT GROUP BY 1, 2
UNION ALL SELECT 'PRODUCT', _CDC_OP, COUNT(*), MAX(_CDC_COMMIT_TS), MAX(_LOADED_AT) FROM RAW.PRODUCT_CT GROUP BY 1, 2
UNION ALL SELECT 'SALESORDERHEADER', _CDC_OP, COUNT(*), MAX(_CDC_COMMIT_TS), MAX(_LOADED_AT) FROM RAW.SALESORDERHEADER_CT GROUP BY 1, 2
UNION ALL SELECT 'SALESORDERDETAIL', _CDC_OP, COUNT(*), MAX(_CDC_COMMIT_TS), MAX(_LOADED_AT) FROM RAW.SALESORDERDETAIL_CT GROUP BY 1, 2;
