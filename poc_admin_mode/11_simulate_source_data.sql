-- =====================================================================
-- PART 4: EXTRACTOR BOOKKEEPING
-- =====================================================================
INSERT INTO CDC_CHECKPOINT (TABLE_NAME, CAPTURE_INSTANCE, LAST_LSN, LAST_MODE, ROWS_LAST_RUN, UPDATED_AT)
SELECT 'CUSTOMER', 'dbo_Customer', MAX(_CDC_LSN), 'INCREMENTAL', COUNT_IF(_BATCH_ID = 'SIM_INCR_001'), CURRENT_TIMESTAMP() FROM CUSTOMER_CT
UNION ALL
SELECT 'PRODUCT', 'dbo_Product', MAX(_CDC_LSN), 'INCREMENTAL', COUNT_IF(_BATCH_ID = 'SIM_INCR_001'), CURRENT_TIMESTAMP() FROM PRODUCT_CT
UNION ALL
SELECT 'SALESORDERHEADER', 'dbo_SalesOrderHeader', MAX(_CDC_LSN), 'INCREMENTAL', COUNT_IF(_BATCH_ID = 'SIM_INCR_001'), CURRENT_TIMESTAMP() FROM SALESORDERHEADER_CT
UNION ALL
SELECT 'SALESORDERDETAIL', 'dbo_SalesOrderDetail', MAX(_CDC_LSN), 'INCREMENTAL', COUNT_IF(_BATCH_ID = 'SIM_INCR_001'), CURRENT_TIMESTAMP() FROM SALESORDERDETAIL_CT;

INSERT INTO LOAD_WATERMARK (TABLE_NAME, HIGH_WATERMARK, ROWS_LOADED, UPDATED_AT)
SELECT 'CUSTOMER', MAX(MODIFIEDDATE), COUNT(*), CURRENT_TIMESTAMP() FROM CUSTOMER
UNION ALL SELECT 'PRODUCT', MAX(MODIFIEDDATE), COUNT(*), CURRENT_TIMESTAMP() FROM PRODUCT
UNION ALL SELECT 'SALESORDERHEADER', MAX(MODIFIEDDATE), COUNT(*), CURRENT_TIMESTAMP() FROM SALESORDERHEADER
UNION ALL SELECT 'SALESORDERDETAIL', MAX(MODIFIEDDATE), COUNT(*), CURRENT_TIMESTAMP() FROM SALESORDERDETAIL;

