-- =====================================================================
-- 11 SIMULATED SOURCE DATA (no SQL Server)
-- Fills SALES_DW_PROD.RAW as if the extractor had run against SalesOLTP:
--   1. *_CT tables: an initial snapshot (_CDC_OP = 'S'), then one batch of
--      CDC changes (I = insert, U = update, D = delete), in LSN order.
--   2. Plain RAW tables: the resulting current state (latest change wins, deletes removed).
--   3. CDC_CHECKPOINT and LOAD_WATERMARK, as the extractor would leave them.
-- Re-runnable: it truncates the RAW tables first. If dbt has already built
-- incremental models from older data, run dbt with --full-refresh afterwards.
--
-- Edge cases for dbt cleansing, rejects (int_order_lines_rejected) and tests:
--   Customers: NULL email/phone/segment, NULL city+country, untrimmed upper-case emails,
--              lower-case country codes, accented and apostrophe names
--   Products:  NULL category/subcategory, inactive, cost > price
--   Orders:    open/shipped/cancelled, EUR/GBP, leap-day and year-end timestamps,
--              10 orders with no lines, 4 orders whose customer does not exist
--   Lines:     zero and negative quantity, zero and negative unit price,
--              discount over 100%, lines whose product does not exist
--   CDC:       inserts, updates (one customer updated twice), deletes of
--              customers/products/orders/lines
-- =====================================================================
USE ROLE POC_ADMIN;
USE WAREHOUSE WH_LOAD;
USE SCHEMA SALES_DW_PROD.RAW;

