TRUNCATE TABLE IF EXISTS SALESORDERDETAIL;
TRUNCATE TABLE IF EXISTS CDC_CHECKPOINT;
TRUNCATE TABLE IF EXISTS LOAD_WATERMARK;

CREATE OR REPLACE TEMPORARY TABLE NUMS AS
SELECT ROW_NUMBER() OVER (ORDER BY SEQ4()) AS I
FROM TABLE(GENERATOR(ROWCOUNT => 5000));

-- =====================================================================
-- PART 1: INITIAL SNAPSHOT (_CDC_OP = 'S', LSN ...1000)
