-- ---------- Order headers (5,000) ----------
INSERT INTO SALESORDERHEADER_CT (SALESORDERID, ORDERNUMBER, CUSTOMERID, ORDERDATE, STATUS, CHANNEL, CURRENCYCODE,
                                 MODIFIEDDATE, _CDC_OP, _CDC_LSN, _CDC_SEQVAL, _CDC_COMMIT_TS, _BATCH_ID)
SELECT
    I,
    'SO' || LPAD(I::VARCHAR, 6, '0'),
    CASE WHEN MOD(I, 1250) = 0 THEN 9999                -- customer that does not exist
         ELSE MOD(I * 7919, 500) + 1 END,
    OD,
    CASE WHEN MOD(I, 20) = 0 THEN 3 WHEN MOD(I, 4) = 0 THEN 1 ELSE 2 END,   -- 3=Cancelled 1=Open 2=Shipped
    DECODE(MOD(I, 3), 0, 'Web', 1, 'Store', 'Partner'),
    CASE WHEN MOD(I, 10) = 0 THEN 'EUR' WHEN MOD(I, 15) = 0 THEN 'GBP' ELSE 'USD' END,
    OD,
    'S', LPAD('1000', 20, '0'), LPAD(I::VARCHAR, 20, '0'), '2026-07-01 00:00:00', 'SIM_SNAPSHOT_001'
FROM (
    SELECT I,
           CASE WHEN MOD(I, 1000) = 0 THEN '2024-02-29 23:59:59.997'::TIMESTAMP_NTZ   -- leap day
                WHEN MOD(I, 1000) = 1 THEN '2025-12-31 23:59:59.997'::TIMESTAMP_NTZ   -- year end
                ELSE DATEADD(MINUTE, MOD(I * 104729, 912 * 1440), '2024-01-01 00:00:00'::TIMESTAMP_NTZ) END AS OD
    FROM NUMS WHERE I <= 5000
);

-- ---------- Order lines (12,490) ----------
-- 1 to 4 lines per order; orders whose ID is a multiple of 500 have no lines.
INSERT INTO SALESORDERDETAIL_CT (SALESORDERDETAILID, SALESORDERID, PRODUCTID, ORDERQTY, UNITPRICE, UNITPRICEDISCOUNT,
                                 MODIFIEDDATE, _CDC_OP, _CDC_LSN, _CDC_SEQVAL, _CDC_COMMIT_TS, _BATCH_ID)
SELECT
    L.RN,
    L.SALESORDERID,
    L.PRODUCTID,
    CASE WHEN MOD(L.RN, 997)  = 0 THEN 0                -- zero quantity
         WHEN MOD(L.RN, 1499) = 0 THEN -2               -- negative quantity
         ELSE 1 + MOD(L.RN, 5) END,
    CASE WHEN MOD(L.RN, 1999) = 0 THEN 0                -- zero price
         WHEN MOD(L.RN, 2999) = 0 THEN -5               -- negative price
         ELSE COALESCE(P.LISTPRICE, 19.99) END,
    CASE WHEN MOD(L.RN, 2503) = 0 THEN 1.50             -- discount over 100%
         WHEN MOD(L.RN, 10)   = 0 THEN 0.10
         WHEN MOD(L.RN, 7)    = 0 THEN 0.05
         ELSE 0 END,
    L.MODIFIEDDATE,
    'S', LPAD('1000', 20, '0'), LPAD(L.RN::VARCHAR, 20, '0'), '2026-07-01 00:00:00', 'SIM_SNAPSHOT_001'
FROM (
    SELECT B.*,
           CASE WHEN MOD(B.RN, 1777) = 0 THEN 999       -- product that does not exist
                ELSE MOD(B.SALESORDERID * 31 + B.K * 17, 100) + 1 END AS PRODUCTID
    FROM (
        SELECT H.SALESORDERID, H.MODIFIEDDATE, K.I AS K,
               ROW_NUMBER() OVER (ORDER BY H.SALESORDERID, K.I) AS RN
        FROM SALESORDERHEADER_CT H
        JOIN NUMS K ON K.I <= 1 + MOD(H.SALESORDERID, 4)
        WHERE H._CDC_OP = 'S' AND MOD(H.SALESORDERID, 500) <> 0
    ) B
) L
LEFT JOIN PRODUCT_CT P ON P.PRODUCTID = L.PRODUCTID AND P._CDC_OP = 'S';

