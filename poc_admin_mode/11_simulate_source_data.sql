-- ---------- Customers (500) ----------
INSERT INTO CUSTOMER_CT (CUSTOMERID, CUSTOMERCODE, FIRSTNAME, LASTNAME, EMAIL, PHONE, CITY, COUNTRYCODE,
                         SEGMENT, MODIFIEDDATE, _CDC_OP, _CDC_LSN, _CDC_SEQVAL, _CDC_COMMIT_TS, _BATCH_ID)
SELECT
    I,
    'C' || LPAD(I::VARCHAR, 5, '0'),
    FN,
    LN,
    CASE WHEN MOD(I, 25) = 0 THEN NULL
         WHEN MOD(I, 33) = 0 THEN '  ' || UPPER(FN || '.' || LN) || '@EXAMPLE.COM  '
         ELSE LOWER(FN || '.' || LN) || I || '@example.com' END,
    CASE WHEN MOD(I, 20) = 0 THEN NULL ELSE '+1-555-' || LPAD(I::VARCHAR, 4, '0') END,
    CASE WHEN MOD(I, 50) = 0 THEN NULL ELSE CITY END,
    CASE WHEN MOD(I, 50) = 0 THEN NULL
         WHEN MOD(I, 77) = 0 THEN LOWER(CC)
         ELSE CC END,
    CASE WHEN MOD(I, 40) = 0 THEN NULL
         ELSE DECODE(MOD(I, 3), 0, 'Consumer', 1, 'Corporate', 'SMB') END,
    DATEADD(DAY, -MOD(I, 365), '2026-06-30 12:00:00'::TIMESTAMP_NTZ),
    'S', LPAD('1000', 20, '0'), LPAD(I::VARCHAR, 20, '0'), '2026-07-01 00:00:00', 'SIM_SNAPSHOT_001'
FROM (
    SELECT I,
           DECODE(MOD(I, 10), 0, 'James', 1, 'Maria', 2, 'Wei', 3, 'Aisha', 4, 'José',
                              5, 'Zoë', 6, 'Rahul', 7, 'Søren', 8, 'Emma', 'Liam') AS FN,
           DECODE(MOD(FLOOR(I / 10), 10), 0, 'Smith', 1, 'García', 2, 'Chen', 3, 'Khan', 4, 'Müller',
                                          5, 'O''Brien', 6, 'Patel', 7, 'Nguyen', 8, 'Rossi', 'Johnson') AS LN,
           DECODE(MOD(I, 8), 0, 'Seattle', 1, 'London', 2, 'Berlin', 3, 'Paris',
                             4, 'Hyderabad', 5, 'Sydney', 6, 'Toronto', 'Tokyo') AS CITY,
           DECODE(MOD(I, 8), 0, 'US', 1, 'GB', 2, 'DE', 3, 'FR', 4, 'IN', 5, 'AU', 6, 'CA', 'JP') AS CC
    FROM NUMS WHERE I <= 500
);

-- ---------- Products (100) ----------
INSERT INTO PRODUCT_CT (PRODUCTID, SKU, PRODUCTNAME, CATEGORY, SUBCATEGORY, LISTPRICE, STANDARDCOST, ISACTIVE,
