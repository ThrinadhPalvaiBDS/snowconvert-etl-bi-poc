USE ROLE POC_ADMIN;
USE SECONDARY ROLES ALL;
USE SCHEMA SALES_DW_PROD.AUDIT;

CREATE TABLE IF NOT EXISTS PIPELINE_RUN (
  RUN_GROUP_ID VARCHAR, PIPELINE VARCHAR, STATUS VARCHAR,
  STARTED_AT TIMESTAMP_LTZ, FINISHED_AT TIMESTAMP_LTZ, ERROR_DETAIL VARCHAR
);

-- Populated by the dbt on-run-end hook (macros/log_run_results.sql)
CREATE TABLE IF NOT EXISTS DBT_RUN_RESULTS (
  INVOCATION_ID VARCHAR, NODE_ID VARCHAR, RESOURCE_TYPE VARCHAR, STATUS VARCHAR,
  EXECUTION_TIME_S FLOAT, ROWS_AFFECTED NUMBER, MESSAGE VARCHAR, RUN_AT TIMESTAMP_LTZ
);

GRANT INSERT, SELECT ON TABLE DBT_RUN_RESULTS TO ROLE TRANSFORMER;
GRANT INSERT, SELECT, UPDATE ON TABLE PIPELINE_RUN TO ROLE TRANSFORMER;

-- SLA + success-rate view for the POC readout
CREATE OR REPLACE VIEW V_PIPELINE_SLA AS
SELECT PIPELINE, DATE(STARTED_AT) AS RUN_DATE, STATUS,
       DATEDIFF('minute', STARTED_AT, FINISHED_AT) AS DURATION_MIN,
       IFF(DATEDIFF('minute', STARTED_AT, FINISHED_AT) <= 60, 'MET', 'BREACHED') AS SLA_60MIN
FROM PIPELINE_RUN;

-- Credit consumption per workload (ACCOUNT_USAGE has latency up to a few hours)
CREATE OR REPLACE VIEW V_WAREHOUSE_COST AS
SELECT WAREHOUSE_NAME, DATE(START_TIME) AS USAGE_DATE, SUM(CREDITS_USED) AS CREDITS
FROM SNOWFLAKE.ACCOUNT_USAGE.WAREHOUSE_METERING_HISTORY
WHERE WAREHOUSE_NAME IN ('WH_LOAD', 'WH_TRANSFORM', 'WH_BI')
  AND START_TIME >= DATEADD('day', -30, CURRENT_TIMESTAMP())
GROUP BY 1, 2;

-- Power BI query performance after cutover
CREATE OR REPLACE VIEW V_POWERBI_QUERY_PERF AS
SELECT DATE(START_TIME) AS QUERY_DATE, USER_NAME, WAREHOUSE_NAME,
       COUNT(*) AS QUERIES,
       APPROX_PERCENTILE(TOTAL_ELAPSED_TIME / 1000, 0.5)  AS P50_S,
       APPROX_PERCENTILE(TOTAL_ELAPSED_TIME / 1000, 0.95) AS P95_S
FROM SNOWFLAKE.ACCOUNT_USAGE.QUERY_HISTORY
WHERE WAREHOUSE_NAME = 'WH_BI' AND START_TIME >= DATEADD('day', -14, CURRENT_TIMESTAMP())
GROUP BY 1, 2, 3;

