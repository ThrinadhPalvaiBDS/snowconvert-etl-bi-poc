-- =====================================================================
-- 01 BOOTSTRAP WITH POC_ADMIN (replaces snowflake/00_account_bootstrap.sql)
-- POC_ADMIN: CREATE DATABASE / WAREHOUSE / INTEGRATION, EXECUTE TASK / ALERT.
-- USERADMIN: CREATE ROLE / CREATE USER.  No ACCOUNTADMIN needed.
-- Schemas are MANAGED ACCESS so POC_ADMIN (schema owner) can define future grants
-- without the account-level MANAGE GRANTS privilege.
-- Not possible with these privileges: resource monitor, network policy (see README).
-- =====================================================================

-- ---------- 1. Functional roles + service users (USERADMIN) ----------
USE ROLE USERADMIN;
CREATE ROLE IF NOT EXISTS LOADER        COMMENT = 'Writes RAW (ingestion)';
CREATE ROLE IF NOT EXISTS TRANSFORMER   COMMENT = 'dbt: reads RAW, writes STAGING..DBO';
CREATE ROLE IF NOT EXISTS BI_READER     COMMENT = 'Power BI: read MARTS + DBO compat';
CREATE ROLE IF NOT EXISTS DATA_ENGINEER COMMENT = 'Humans: dev + read prod';
CREATE ROLE IF NOT EXISTS PII_READER    COMMENT = 'Sees unmasked PII';
GRANT ROLE LOADER, TRANSFORMER, BI_READER, DATA_ENGINEER, PII_READER TO ROLE POC_ADMIN;

-- Reuse the service users the admin already created
GRANT ROLE LOADER, TRANSFORMER TO USER SVC_POC_PIPELINE;
ALTER USER SVC_POC_PIPELINE SET DEFAULT_ROLE = TRANSFORMER DEFAULT_WAREHOUSE = WH_TRANSFORM;
GRANT ROLE BI_READER TO USER SVC_POC_POWERBI;
ALTER USER SVC_POC_POWERBI SET DEFAULT_ROLE = BI_READER DEFAULT_WAREHOUSE = WH_BI
  DEFAULT_NAMESPACE = 'SALES_DW_PROD.DBO';
-- ALTER USER SVC_POC_PIPELINE SET RSA_PUBLIC_KEY = '<svc_poc_pipeline.pub contents>';

-- ---------- 2. Warehouses + databases (POC_ADMIN) ----------
USE ROLE POC_ADMIN;
USE SECONDARY ROLES ALL;

CREATE WAREHOUSE IF NOT EXISTS WH_LOAD      WAREHOUSE_SIZE = XSMALL AUTO_SUSPEND = 60  AUTO_RESUME = TRUE INITIALLY_SUSPENDED = TRUE;
CREATE WAREHOUSE IF NOT EXISTS WH_TRANSFORM WAREHOUSE_SIZE = SMALL  AUTO_SUSPEND = 60  AUTO_RESUME = TRUE INITIALLY_SUSPENDED = TRUE;
CREATE WAREHOUSE IF NOT EXISTS WH_BI        WAREHOUSE_SIZE = SMALL  AUTO_SUSPEND = 300 AUTO_RESUME = TRUE INITIALLY_SUSPENDED = TRUE
  MIN_CLUSTER_COUNT = 1 MAX_CLUSTER_COUNT = 2 SCALING_POLICY = STANDARD;

CREATE DATABASE IF NOT EXISTS SALES_DW_DEV;
CREATE DATABASE IF NOT EXISTS SALES_DW_PROD;
CREATE DATABASE IF NOT EXISTS PLATFORM COMMENT = 'Integrations objects, git repos, dbt project, governance';

CREATE SCHEMA IF NOT EXISTS SALES_DW_PROD.RAW          WITH MANAGED ACCESS;
CREATE SCHEMA IF NOT EXISTS SALES_DW_PROD.STAGING      WITH MANAGED ACCESS;
CREATE SCHEMA IF NOT EXISTS SALES_DW_PROD.INTERMEDIATE WITH MANAGED ACCESS;
CREATE SCHEMA IF NOT EXISTS SALES_DW_PROD.SNAPSHOTS    WITH MANAGED ACCESS;
CREATE SCHEMA IF NOT EXISTS SALES_DW_PROD.MARTS        WITH MANAGED ACCESS;
CREATE SCHEMA IF NOT EXISTS SALES_DW_PROD.DBO          WITH MANAGED ACCESS COMMENT = 'Legacy-compatible views for repointed Power BI';
CREATE SCHEMA IF NOT EXISTS SALES_DW_PROD.AUDIT        WITH MANAGED ACCESS;
CREATE SCHEMA IF NOT EXISTS SALES_DW_DEV.RAW;
CREATE SCHEMA IF NOT EXISTS PLATFORM.INTEGRATIONS      WITH MANAGED ACCESS;
CREATE SCHEMA IF NOT EXISTS PLATFORM.DBT               WITH MANAGED ACCESS;
CREATE SCHEMA IF NOT EXISTS PLATFORM.GOVERNANCE        WITH MANAGED ACCESS;

-- ---------- 3. Privileges ----------
GRANT USAGE ON WAREHOUSE WH_LOAD      TO ROLE LOADER;
GRANT USAGE ON WAREHOUSE WH_TRANSFORM TO ROLE TRANSFORMER;
GRANT USAGE ON WAREHOUSE WH_BI        TO ROLE BI_READER;
GRANT USAGE, OPERATE ON WAREHOUSE WH_TRANSFORM TO ROLE DATA_ENGINEER;

-- LOADER: RAW only
GRANT USAGE ON DATABASE SALES_DW_PROD TO ROLE LOADER;
GRANT USAGE, CREATE TABLE, CREATE STAGE, CREATE PIPE, CREATE PROCEDURE, CREATE FILE FORMAT
  ON SCHEMA SALES_DW_PROD.RAW TO ROLE LOADER;
GRANT SELECT, INSERT, UPDATE, DELETE, TRUNCATE ON FUTURE TABLES IN SCHEMA SALES_DW_PROD.RAW TO ROLE LOADER;

-- TRANSFORMER: read RAW, build modelled schemas
GRANT USAGE ON DATABASE SALES_DW_PROD TO ROLE TRANSFORMER;
GRANT USAGE ON SCHEMA SALES_DW_PROD.RAW TO ROLE TRANSFORMER;
GRANT SELECT ON FUTURE TABLES IN SCHEMA SALES_DW_PROD.RAW TO ROLE TRANSFORMER;
GRANT USAGE, CREATE TABLE, CREATE VIEW ON SCHEMA SALES_DW_PROD.STAGING      TO ROLE TRANSFORMER;
GRANT USAGE, CREATE TABLE, CREATE VIEW ON SCHEMA SALES_DW_PROD.INTERMEDIATE TO ROLE TRANSFORMER;
GRANT USAGE, CREATE TABLE, CREATE VIEW ON SCHEMA SALES_DW_PROD.SNAPSHOTS    TO ROLE TRANSFORMER;
GRANT USAGE, CREATE TABLE, CREATE VIEW ON SCHEMA SALES_DW_PROD.MARTS        TO ROLE TRANSFORMER;
GRANT USAGE, CREATE TABLE, CREATE VIEW ON SCHEMA SALES_DW_PROD.DBO          TO ROLE TRANSFORMER;
GRANT USAGE, CREATE TABLE ON SCHEMA SALES_DW_PROD.AUDIT TO ROLE TRANSFORMER;
GRANT ALL ON DATABASE SALES_DW_DEV TO ROLE TRANSFORMER;
GRANT ALL ON DATABASE SALES_DW_DEV TO ROLE DATA_ENGINEER;

-- BI_READER: presentation layers only
GRANT USAGE ON DATABASE SALES_DW_PROD TO ROLE BI_READER;
GRANT USAGE ON SCHEMA SALES_DW_PROD.MARTS TO ROLE BI_READER;
GRANT USAGE ON SCHEMA SALES_DW_PROD.DBO   TO ROLE BI_READER;
GRANT SELECT ON FUTURE TABLES IN SCHEMA SALES_DW_PROD.MARTS TO ROLE BI_READER;
GRANT SELECT ON FUTURE VIEWS  IN SCHEMA SALES_DW_PROD.MARTS TO ROLE BI_READER;
GRANT SELECT ON FUTURE VIEWS  IN SCHEMA SALES_DW_PROD.DBO   TO ROLE BI_READER;

-- dbt project + git objects are owned by TRANSFORMER so CI (SVC_POC_PIPELINE) can add versions
GRANT USAGE ON DATABASE PLATFORM TO ROLE TRANSFORMER;
GRANT USAGE, CREATE DBT PROJECT ON SCHEMA PLATFORM.DBT TO ROLE TRANSFORMER;
GRANT USAGE ON SCHEMA PLATFORM.INTEGRATIONS TO ROLE TRANSFORMER;
GRANT USAGE ON SCHEMA PLATFORM.GOVERNANCE TO ROLE TRANSFORMER;

-- ---------- 4. Integrations owned by POC_ADMIN (so their USAGE can be granted onward) ----------
CREATE API INTEGRATION IF NOT EXISTS POC_ADMIN_GIT_API
  API_PROVIDER = GIT_HTTPS_API
  API_ALLOWED_PREFIXES = ('https://github.com/ThrinadhPalvaiBDS/')
  ALLOWED_AUTHENTICATION_SECRETS = ALL
  ENABLED = TRUE;

CREATE NETWORK RULE IF NOT EXISTS PLATFORM.INTEGRATIONS.DBT_DEPS_EGRESS
  MODE = EGRESS TYPE = HOST_PORT VALUE_LIST = ('hub.getdbt.com', 'codeload.github.com');
CREATE EXTERNAL ACCESS INTEGRATION IF NOT EXISTS DBT_DEPS_EAI
  ALLOWED_NETWORK_RULES = (PLATFORM.INTEGRATIONS.DBT_DEPS_EGRESS) ENABLED = TRUE;
GRANT USAGE ON INTEGRATION DBT_DEPS_EAI TO ROLE TRANSFORMER;

CREATE NOTIFICATION INTEGRATION IF NOT EXISTS NI_DATA_OPS_EMAIL
  TYPE = EMAIL ENABLED = TRUE ALLOWED_RECIPIENTS = ('thrinadhp@booleandata.ai');
