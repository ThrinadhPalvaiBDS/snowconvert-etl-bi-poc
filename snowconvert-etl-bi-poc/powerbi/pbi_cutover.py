"""
Power BI cutover automation for SnowConvert-repointed reports.

Per report:  import .pbix -> take over -> set Snowflake parameters -> bind credentials
             -> refresh -> verify. Writes a JSON cutover log used in the go/no-go review.
Report visuals, measures and RLS are untouched: that is the "no rebuild" guarantee.
"""
import argparse
import json
import logging
import os
from datetime import datetime, timezone

import yaml

from pbi_client import PowerBIClient

logging.basicConfig(level=logging.INFO, format="%(asctime)s %(levelname)s %(message)s")
log = logging.getLogger("cutover")


def cutover_report(pbi, cfg, rpt, dry_run=False):
    g, name = rpt["target_workspace_id"], rpt["name"]
    result = {"report": name, "workspace": g, "steps": []}

    if dry_run:
        log.info("[dry-run] would import %s into %s", rpt["pbix_path"], g)
        return result

    imp = pbi.import_pbix(g, rpt["pbix_path"], name)
    dataset_id = imp["datasets"][0]["id"]
    result.update(dataset_id=dataset_id, report_id=imp["reports"][0]["id"])
    result["steps"].append("imported")

    pbi.take_over(g, dataset_id)
    result["steps"].append("took_over")

    existing = {p["name"] for p in pbi.get_parameters(g, dataset_id)}
    wanted = cfg["snowflake"]["parameters"]
    missing = set(wanted) - existing
    if missing:
        log.warning("%s: parameters %s not found in model (names generated by repointing may differ "
                    "- update cutover_config.yaml). Existing: %s", name, missing, sorted(existing))
    to_set = {k: v for k, v in wanted.items() if k in existing}
    if to_set:
        pbi.update_parameters(g, dataset_id, to_set)
        result["steps"].append(f"parameters:{sorted(to_set)}")

    cred = cfg["snowflake"]["credential"]
    for ds in pbi.get_datasources(g, dataset_id):
        if "snowflake" not in json.dumps(ds).lower():
            log.warning("%s: non-Snowflake datasource still present: %s", name, ds)
            result.setdefault("warnings", []).append(f"non-snowflake datasource {ds.get('datasourceType')}")
            continue
        if cred["type"] == "Basic":
            pbi.set_basic_credentials(ds["gatewayId"], ds["datasourceId"],
                                      os.environ[cred["username_env"]], os.environ[cred["password_env"]])
            result["steps"].append(f"credentials:{ds['datasourceId']}")
        else:
            log.info("%s: OAuth2/SSO credentials are set once in the Service UI (Edit credentials)", name)

    if rpt.get("refresh", True):
        last = pbi.refresh(g, dataset_id)
        result["refresh_status"] = last["status"]
        if last["status"] != "Completed":
            result["refresh_error"] = last.get("serviceExceptionJson")
            raise RuntimeError(f"{name}: refresh {last['status']}: {last.get('serviceExceptionJson')}")
        result["steps"].append("refreshed")

    log.info("%s: cutover complete (dataset %s)", name, dataset_id)
    return result


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--config", required=True)
    ap.add_argument("--only", help="report name to process")
    ap.add_argument("--dry-run", action="store_true")
    args = ap.parse_args()

    cfg = yaml.safe_load(open(args.config))
    pbi = PowerBIClient.from_config(cfg)
    results, failed = [], False
    for rpt in cfg["reports"]:
        if args.only and rpt["name"] != args.only:
            continue
        try:
            results.append(cutover_report(pbi, cfg, rpt, args.dry_run))
        except Exception as exc:  # keep going, report at the end
            failed = True
            log.error("%s: FAILED - %s", rpt["name"], exc)
            results.append({"report": rpt["name"], "error": str(exc)})

    out = f"powerbi/cutover_log_{datetime.now(timezone.utc):%Y%m%dT%H%M%S}.json"
    with open(out, "w") as fh:
        json.dump(results, fh, indent=2)
    log.info("cutover log -> %s", out)
    raise SystemExit(1 if failed else 0)


if __name__ == "__main__":
    main()
