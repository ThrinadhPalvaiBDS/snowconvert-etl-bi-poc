-- =====================================================================
-- 00 ACCOUNT BOOTSTRAP: roles, warehouses, databases, resource monitors
-- Run as ACCOUNTADMIN (once per environment). Idempotent.
-- =====================================================================
USE ROLE SECURITYADMIN;

-- Functional roles
CREATE ROLE IF NOT EXISTS PLATFORM_ADMIN  COMMENT = 'Owns POC databases/warehouses';
CREATE ROLE IF NOT EXISTS LOADER          COMMENT = 'Writes RAW (ingestion)';
CREATE ROLE IF NOT EXISTS TRANSFORMER     COMMENT = 'dbt: reads RAW, writes STAGING..DBO';
CREATE ROLE IF NOT EXISTS BI_READER       COMMENT = 'Power BI: read MARTS + DBO compat';
CREATE ROLE IF NOT EXISTS DATA_ENGINEER   COMMENT = 'Humans: dev + read prod';

GRANT ROLE LOADER, TRANSFORMER, BI_READER, DATA_ENGINEER TO ROLE PLATFORM_ADMIN;
GRANT ROLE PLATFORM_ADMIN TO ROLE SYSADMIN;

USE ROLE SYSADMIN;

-- Warehouses: isolate workloads for cost attribution and concurrency
CREATE WAREHOUSE IF NOT EXISTS WH_LOAD      WAREHOUSE_SIZE = XSMALL AUTO_SUSPEND = 60 AUTO_RESUME = TRUE INITIALLY_SUSPENDED = TRUE;
CREATE WAREHOUSE IF NOT EXISTS WH_TRANSFORM WAREHOUSE_SIZE = SMALL  AUTO_SUSPEND = 60 AUTO_RESUME = TRUE INITIALLY_SUSPENDED = TRUE;
CREATE WAREHOUSE IF NOT EXISTS WH_BI        WAREHOUSE_SIZE = SMALL  AUTO_SUSPEND = 300 AUTO_RESUME = TRUE INITIALLY_SUSPENDED = TRUE
  MIN_CLUSTER_COUNT = 1 MAX_CLUSTER_COUNT = 3 SCALING_POLICY = STANDARD   -- multi-cluster needs Enterprise
  COMMENT = 'Power BI DirectQuery / import refresh';

-- Databases per environment
CREATE DATABASE IF NOT EXISTS SALES_DW_DEV;
CREATE DATABASE IF NOT EXISTS SALES_DW_PROD;
CREATE DATABASE IF NOT EXISTS PLATFORM COMMENT = 'Integrations, git repos, audit, dbt project objects';

-- Schemas (prod shown; dev uses same names, dbt dev targets also add per-user prefixes)
CREATE SCHEMA IF NOT EXISTS SALES_DW_PROD.RAW;
CREATE SCHEMA IF NOT EXISTS SALES_DW_PROD.STAGING;
CREATE SCHEMA IF NOT EXISTS SALES_DW_PROD.INTERMEDIATE;
CREATE SCHEMA IF NOT EXISTS SALES_DW_PROD.SNAPSHOTS;
CREATE SCHEMA IF NOT EXISTS SALES_DW_PROD.MARTS;
CREATE SCHEMA IF NOT EXISTS SALES_DW_PROD.DBO   COMMENT = 'Legacy-compatible views for repointed Power BI';
CREATE SCHEMA IF NOT EXISTS SALES_DW_PROD.AUDIT;
CREATE SCHEMA IF NOT EXISTS SALES_DW_DEV.RAW;
CREATE SCHEMA IF NOT EXISTS PLATFORM.INTEGRATIONS;
CREATE SCHEMA IF NOT EXISTS PLATFORM.DBT;
CREATE SCHEMA IF NOT EXISTS PLATFORM.GOVERNANCE;

-- Ownership + privileges
GRANT OWNERSHIP ON DATABASE SALES_DW_DEV  TO ROLE PLATFORM_ADMIN COPY CURRENT GRANTS;
GRANT OWNERSHIP ON DATABASE SALES_DW_PROD TO ROLE PLATFORM_ADMIN COPY CURRENT GRANTS;
GRANT OWNERSHIP ON DATABASE PLATFORM      TO ROLE PLATFORM_ADMIN COPY CURRENT GRANTS;

GRANT USAGE ON WAREHOUSE WH_LOAD      TO ROLE LOADER;
GRANT USAGE ON WAREHOUSE WH_TRANSFORM TO ROLE TRANSFORMER;
GRANT USAGE ON WAREHOUSE WH_BI        TO ROLE BI_READER;
GRANT USAGE, OPERATE ON WAREHOUSE WH_TRANSFORM TO ROLE DATA_ENGINEER;

USE ROLE PLATFORM_ADMIN;
-- LOADER: RAW only
GRANT USAGE ON DATABASE SALES_DW_PROD TO ROLE LOADER;
GRANT USAGE, CREATE TABLE, CREATE STAGE, CREATE PIPE ON SCHEMA SALES_DW_PROD.RAW TO ROLE LOADER;
GRANT SELECT, INSERT, UPDATE, DELETE, TRUNCATE ON FUTURE TABLES IN SCHEMA SALES_DW_PROD.RAW TO ROLE LOADER;

-- TRANSFORMER: read RAW, own modelled schemas
GRANT USAGE ON DATABASE SALES_DW_PROD TO ROLE TRANSFORMER;
GRANT USAGE ON SCHEMA SALES_DW_PROD.RAW TO ROLE TRANSFORMER;
GRANT SELECT ON ALL TABLES IN SCHEMA SALES_DW_PROD.RAW TO ROLE TRANSFORMER;
GRANT SELECT ON FUTURE TABLES IN SCHEMA SALES_DW_PROD.RAW TO ROLE TRANSFORMER;
GRANT USAGE, CREATE TABLE, CREATE VIEW ON SCHEMA SALES_DW_PROD.STAGING      TO ROLE TRANSFORMER;
GRANT USAGE, CREATE TABLE, CREATE VIEW ON SCHEMA SALES_DW_PROD.INTERMEDIATE TO ROLE TRANSFORMER;
GRANT USAGE, CREATE TABLE, CREATE VIEW ON SCHEMA SALES_DW_PROD.SNAPSHOTS    TO ROLE TRANSFORMER;
GRANT USAGE, CREATE TABLE, CREATE VIEW ON SCHEMA SALES_DW_PROD.MARTS        TO ROLE TRANSFORMER;
GRANT USAGE, CREATE TABLE, CREATE VIEW ON SCHEMA SALES_DW_PROD.DBO          TO ROLE TRANSFORMER;
GRANT USAGE, CREATE TABLE ON SCHEMA SALES_DW_PROD.AUDIT TO ROLE TRANSFORMER;
GRANT ALL ON DATABASE SALES_DW_DEV TO ROLE TRANSFORMER;
GRANT ALL ON DATABASE SALES_DW_DEV TO ROLE DATA_ENGINEER;

-- BI_READER: only the presentation layers
GRANT USAGE ON DATABASE SALES_DW_PROD TO ROLE BI_READER;
GRANT USAGE ON SCHEMA SALES_DW_PROD.MARTS TO ROLE BI_READER;
GRANT USAGE ON SCHEMA SALES_DW_PROD.DBO   TO ROLE BI_READER;
GRANT SELECT ON FUTURE TABLES IN SCHEMA SALES_DW_PROD.MARTS TO ROLE BI_READER;
GRANT SELECT ON FUTURE VIEWS  IN SCHEMA SALES_DW_PROD.MARTS TO ROLE BI_READER;
GRANT SELECT ON FUTURE VIEWS  IN SCHEMA SALES_DW_PROD.DBO   TO ROLE BI_READER;

-- Cost guardrails
USE ROLE ACCOUNTADMIN;
CREATE OR REPLACE RESOURCE MONITOR RM_SALES_POC WITH CREDIT_QUOTA = 200 FREQUENCY = MONTHLY
  START_TIMESTAMP = IMMEDIATELY
  TRIGGERS ON 75 PERCENT DO NOTIFY ON 90 PERCENT DO SUSPEND ON 100 PERCENT DO SUSPEND_IMMEDIATE;
ALTER WAREHOUSE WH_LOAD      SET RESOURCE_MONITOR = RM_SALES_POC;
ALTER WAREHOUSE WH_TRANSFORM SET RESOURCE_MONITOR = RM_SALES_POC;
ALTER WAREHOUSE WH_BI        SET RESOURCE_MONITOR = RM_SALES_POC;

-- Service users (key-pair auth; set RSA_PUBLIC_KEY from your vault)
CREATE USER IF NOT EXISTS SVC_LOADER     TYPE = SERVICE DEFAULT_ROLE = LOADER      DEFAULT_WAREHOUSE = WH_LOAD;
CREATE USER IF NOT EXISTS SVC_DBT_DEPLOY TYPE = SERVICE DEFAULT_ROLE = TRANSFORMER DEFAULT_WAREHOUSE = WH_TRANSFORM;
-- ALTER USER SVC_LOADER     SET RSA_PUBLIC_KEY = '<public key>';
-- ALTER USER SVC_DBT_DEPLOY SET RSA_PUBLIC_KEY = '<public key>';
CREATE USER IF NOT EXISTS SVC_CICD       TYPE = SERVICE DEFAULT_ROLE = PLATFORM_ADMIN DEFAULT_WAREHOUSE = WH_TRANSFORM;
-- ALTER USER SVC_CICD SET RSA_PUBLIC_KEY = '<public key>';
GRANT ROLE LOADER         TO USER SVC_LOADER;
GRANT ROLE TRANSFORMER    TO USER SVC_DBT_DEPLOY;
GRANT ROLE PLATFORM_ADMIN TO USER SVC_CICD;
GRANT ROLE TRANSFORMER    TO USER SVC_CICD;     -- dbt compile in CD uses the prod target role

-- Email channel for task finalizer + alerts (replaces SSIS SMTP connection manager)
CREATE NOTIFICATION INTEGRATION IF NOT EXISTS NI_DATA_OPS_EMAIL
  TYPE = EMAIL ENABLED = TRUE
  ALLOWED_RECIPIENTS = ('data-ops@yourcompany.com');
GRANT USAGE ON INTEGRATION NI_DATA_OPS_EMAIL TO ROLE PLATFORM_ADMIN;
GRANT EXECUTE TASK, EXECUTE ALERT ON ACCOUNT TO ROLE PLATFORM_ADMIN;
GRANT IMPORTED PRIVILEGES ON DATABASE SNOWFLAKE TO ROLE PLATFORM_ADMIN;   -- ACCOUNT_USAGE views
