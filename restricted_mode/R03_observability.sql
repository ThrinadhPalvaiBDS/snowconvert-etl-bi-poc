USE ROLE CORTEX_AI_FULL_ACCESS_ROLE;
USE WAREHOUSE CORTEX_AI_WH;
USE SCHEMA CORTEX_AI.DATA;

CREATE OR REPLACE VIEW POC_V_PIPELINE_SLA AS
SELECT PIPELINE, DATE(STARTED_AT) AS RUN_DATE, STATUS,
       DATEDIFF('minute', STARTED_AT, FINISHED_AT) AS DURATION_MIN,
       IFF(DATEDIFF('minute', STARTED_AT, FINISHED_AT) <= 60, 'MET', 'BREACHED') AS SLA_60MIN
FROM POC_PIPELINE_RUN;

CREATE OR REPLACE VIEW POC_V_DBT_MODEL_TIMINGS AS
SELECT RUN_AT::DATE AS RUN_DATE, NODE_ID, STATUS, EXECUTION_TIME_S, ROWS_AFFECTED
FROM POC_DBT_RUN_RESULTS;

-- Whole-warehouse credits (shared with other CORTEX_AI workloads)
CREATE OR REPLACE VIEW POC_V_WAREHOUSE_COST AS
SELECT DATE(START_TIME) AS USAGE_DATE, SUM(CREDITS_USED) AS CREDITS
FROM SNOWFLAKE.ACCOUNT_USAGE.WAREHOUSE_METERING_HISTORY
WHERE WAREHOUSE_NAME = 'CORTEX_AI_WH' AND START_TIME >= DATEADD('day', -30, CURRENT_TIMESTAMP())
GROUP BY 1;

-- POC share of that, by query tag. Needs read access to ACCOUNT_USAGE.QUERY_HISTORY:
-- test first with  SELECT COUNT(*) FROM SNOWFLAKE.ACCOUNT_USAGE.QUERY_HISTORY;
-- If that fails, use the INFORMATION_SCHEMA fallback below instead.
CREATE OR REPLACE VIEW POC_V_QUERY_PERF AS
SELECT DATE(START_TIME) AS QUERY_DATE,
       SPLIT_PART(SPLIT_PART(QUERY_TAG, 'app=', 2), ';', 1) AS APP,
       COUNT(*) AS QUERIES,
       SUM(TOTAL_ELAPSED_TIME) / 1000 AS TOTAL_S,
       APPROX_PERCENTILE(TOTAL_ELAPSED_TIME / 1000, 0.95) AS P95_S
FROM SNOWFLAKE.ACCOUNT_USAGE.QUERY_HISTORY
WHERE WAREHOUSE_NAME = 'CORTEX_AI_WH'
  AND (QUERY_TAG ILIKE '%snowconvert_poc%' OR QUERY_TAG ILIKE 'app=dbt%'
       OR QUERY_TAG ILIKE 'app=ingestion%' OR QUERY_TAG ILIKE 'app=powerbi%')
GROUP BY 1, 2;

