-- =====================================================================
-- R01 RESTRICTED-MODE SETUP (no ACCOUNTADMIN needed)
-- Runs entirely with CORTEX_AI_FULL_ACCESS_ROLE inside CORTEX_AI.DATA.
-- Replaces 00_account_bootstrap.sql + 01_raw_landing.sql.
-- All POC objects carry a prefix (RAW_, STG_, INT_, SNAP_, DIM_, FCT_, POC_)
-- because DATA already holds other projects' objects (CUSTOMERS, ORDERS, RAP_REGION ...).
-- =====================================================================
USE ROLE CORTEX_AI_FULL_ACCESS_ROLE;
USE WAREHOUSE CORTEX_AI_WH;          -- shared XS warehouse; you have USAGE/OPERATE/MONITOR, not MODIFY
USE SCHEMA CORTEX_AI.DATA;

-- Tag every query from this session so POC cost can be separated on the shared warehouse
ALTER SESSION SET QUERY_TAG = 'app=snowconvert_poc;layer=setup';

CREATE FILE FORMAT IF NOT EXISTS POC_FF_PARQUET TYPE = PARQUET;
CREATE STAGE IF NOT EXISTS POC_STG_LANDING FILE_FORMAT = POC_FF_PARQUET
  DIRECTORY = (ENABLE = TRUE) ENCRYPTION = (TYPE = 'SNOWFLAKE_SSE');

CREATE TABLE IF NOT EXISTS RAW_CUSTOMER (
    CUSTOMERID NUMBER(38,0), CUSTOMERCODE VARCHAR(20), FIRSTNAME VARCHAR(50), LASTNAME VARCHAR(50),
    EMAIL VARCHAR(255), PHONE VARCHAR(30), CITY VARCHAR(100), COUNTRYCODE VARCHAR(2), SEGMENT VARCHAR(20),
    MODIFIEDDATE TIMESTAMP_NTZ(3),
    _LOADED_AT TIMESTAMP_LTZ DEFAULT CURRENT_TIMESTAMP(), _BATCH_ID VARCHAR(64), _SOURCE_SYSTEM VARCHAR(30) DEFAULT 'SalesOLTP');

CREATE TABLE IF NOT EXISTS RAW_PRODUCT (
    PRODUCTID NUMBER(38,0), SKU VARCHAR(30), PRODUCTNAME VARCHAR(200), CATEGORY VARCHAR(50), SUBCATEGORY VARCHAR(50),
    LISTPRICE NUMBER(38,4), STANDARDCOST NUMBER(38,4), ISACTIVE BOOLEAN, MODIFIEDDATE TIMESTAMP_NTZ(3),
    _LOADED_AT TIMESTAMP_LTZ DEFAULT CURRENT_TIMESTAMP(), _BATCH_ID VARCHAR(64), _SOURCE_SYSTEM VARCHAR(30) DEFAULT 'SalesOLTP');

CREATE TABLE IF NOT EXISTS RAW_SALESORDERHEADER (
    SALESORDERID NUMBER(38,0), ORDERNUMBER VARCHAR(25), CUSTOMERID NUMBER(38,0), ORDERDATE TIMESTAMP_NTZ(3),
    STATUS NUMBER(3,0), CHANNEL VARCHAR(20), CURRENCYCODE VARCHAR(3), MODIFIEDDATE TIMESTAMP_NTZ(3),
    _LOADED_AT TIMESTAMP_LTZ DEFAULT CURRENT_TIMESTAMP(), _BATCH_ID VARCHAR(64), _SOURCE_SYSTEM VARCHAR(30) DEFAULT 'SalesOLTP');

CREATE TABLE IF NOT EXISTS RAW_SALESORDERDETAIL (
    SALESORDERDETAILID NUMBER(38,0), SALESORDERID NUMBER(38,0), PRODUCTID NUMBER(38,0), ORDERQTY NUMBER(5,0),
    UNITPRICE NUMBER(38,4), UNITPRICEDISCOUNT NUMBER(38,4), MODIFIEDDATE TIMESTAMP_NTZ(3),
    _LOADED_AT TIMESTAMP_LTZ DEFAULT CURRENT_TIMESTAMP(), _BATCH_ID VARCHAR(64), _SOURCE_SYSTEM VARCHAR(30) DEFAULT 'SalesOLTP');

CREATE TABLE IF NOT EXISTS POC_LOAD_WATERMARK (
    TABLE_NAME VARCHAR(128) PRIMARY KEY, HIGH_WATERMARK TIMESTAMP_NTZ(3), ROWS_LOADED NUMBER, UPDATED_AT TIMESTAMP_LTZ);

-- Audit (replaces AUDIT schema)
CREATE TABLE IF NOT EXISTS POC_PIPELINE_RUN (
    RUN_ID VARCHAR, PIPELINE VARCHAR, STATUS VARCHAR,
    STARTED_AT TIMESTAMP_LTZ, FINISHED_AT TIMESTAMP_LTZ, ERROR_DETAIL VARCHAR);
CREATE TABLE IF NOT EXISTS POC_DBT_RUN_RESULTS (
    INVOCATION_ID VARCHAR, NODE_ID VARCHAR, RESOURCE_TYPE VARCHAR, STATUS VARCHAR,
    EXECUTION_TIME_S FLOAT, ROWS_AFFECTED NUMBER, MESSAGE VARCHAR, RUN_AT TIMESTAMP_LTZ);

-- Sanity check: no name clashes with existing objects in DATA
SHOW TABLES LIKE 'RAW\\_%' IN SCHEMA CORTEX_AI.DATA;
SHOW TABLES LIKE 'POC\\_%' IN SCHEMA CORTEX_AI.DATA;
