-- =====================================================================
-- 03 DEPLOY dbt PROJECT INTO SNOWFLAKE (dbt Projects on Snowflake)
-- Git repo -> Snowflake GIT REPOSITORY -> DBT PROJECT object -> EXECUTE DBT PROJECT
-- =====================================================================
USE ROLE ACCOUNTADMIN;

-- 1) Git connectivity (GitHub example; PAT stored as a secret)
CREATE OR REPLACE SECRET PLATFORM.INTEGRATIONS.GH_PAT
  TYPE = PASSWORD USERNAME = 'svc-snowflake-git' PASSWORD = '<github_pat_from_vault>';

CREATE OR REPLACE API INTEGRATION GIT_API_INTEGRATION
  API_PROVIDER = GIT_HTTPS_API
  API_ALLOWED_PREFIXES = ('https://github.com/your-org/')
  ALLOWED_AUTHENTICATION_SECRETS = (PLATFORM.INTEGRATIONS.GH_PAT)
  ENABLED = TRUE;
GRANT USAGE ON INTEGRATION GIT_API_INTEGRATION TO ROLE PLATFORM_ADMIN;

-- 2) dbt deps needs egress to hub.getdbt.com / github for packages
CREATE OR REPLACE NETWORK RULE PLATFORM.INTEGRATIONS.DBT_DEPS_EGRESS
  MODE = EGRESS TYPE = HOST_PORT
  VALUE_LIST = ('hub.getdbt.com', 'codeload.github.com');
CREATE OR REPLACE EXTERNAL ACCESS INTEGRATION DBT_DEPS_EAI
  ALLOWED_NETWORK_RULES = (PLATFORM.INTEGRATIONS.DBT_DEPS_EGRESS) ENABLED = TRUE;
GRANT USAGE ON INTEGRATION DBT_DEPS_EAI TO ROLE PLATFORM_ADMIN;

USE ROLE PLATFORM_ADMIN;
CREATE OR REPLACE GIT REPOSITORY PLATFORM.INTEGRATIONS.SNOWCONVERT_POC_REPO
  API_INTEGRATION = GIT_API_INTEGRATION
  GIT_CREDENTIALS = PLATFORM.INTEGRATIONS.GH_PAT
  ORIGIN = 'https://github.com/your-org/snowconvert-etl-bi-poc.git';

ALTER GIT REPOSITORY PLATFORM.INTEGRATIONS.SNOWCONVERT_POC_REPO FETCH;

-- 3) Create / version the dbt project object from the repo's dbt/ folder
CREATE OR REPLACE DBT PROJECT PLATFORM.DBT.SALES_DW
  FROM '@PLATFORM.INTEGRATIONS.SNOWCONVERT_POC_REPO/branches/main/dbt'
  EXTERNAL_ACCESS_INTEGRATIONS = (DBT_DEPS_EAI)
  COMMENT = 'Replatformed Load_SalesDW (SSIS) - SnowConvert AI POC';

GRANT USAGE ON DBT PROJECT PLATFORM.DBT.SALES_DW TO ROLE TRANSFORMER;

-- 4) Smoke run (the Task DAG in 04 runs this on schedule)
EXECUTE DBT PROJECT PLATFORM.DBT.SALES_DW ARGS = 'build --target prod';
